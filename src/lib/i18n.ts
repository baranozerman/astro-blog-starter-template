const TABLES: Record<Lang, Record<MessageKey, string>> = { tr, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
	const table = TABLES[lang];
	return (key, vars) => {
		let text = table[key] ?? tr[key] ?? key;
		if (text.includes("|")) text = text.split("|")[vars?.n === 1 ? 0 : 1];
		return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : text;
	};
}

/** The untranslated template (placeholders and plural forms intact), for browser-side code. */
export function rawMessage(lang: Lang, key: MessageKey) {
	return TABLES[lang][key] ?? tr[key];
}

export function isMessageKey(key: string): key is MessageKey {
	return key in tr;
}

/** Cookie choice first, then the browser's preferred language (Turkish → tr, anything else → en). */
export function detectLang(cookie: string | undefined, acceptLanguage: string | null): Lang {
	if (cookie === "tr" || cookie === "en") return cookie;
	const first = (acceptLanguage ?? "").split(",")[0]?.trim().toLowerCase() ?? "";
	return first.startsWith("tr") ? "tr" : "en";
}

